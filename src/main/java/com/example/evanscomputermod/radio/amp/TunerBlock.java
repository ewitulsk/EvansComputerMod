/**
 * Antenna tuner: an inline coax block between the amplifier and the antenna
 * that matches the antenna's impedance, so the amplifier sees SWR of about 1:1
 * (up to {@link AmpModel#TUNER_MAX_SWR}). It can't fix an inefficient
 * antenna: the mismatch power is absorbed in the tuner as heat instead of
 * reflecting into the amplifier. Rated {@link AmpModel#TUNER_RATING_W} of
 * dissipation.
 */
public class TunerBlock extends BaseEntityBlock {
    public static final DirectionProperty FACING = BlockStateProperties.HORIZONTAL_FACING;
    /** A full cube: TX jack on the back face, ANT feedthrough on top, coax sockets on the sides. */
    private static final VoxelShape SHAPE = net.minecraft.world.phys.shapes.Shapes.block();

    public TunerBlock(Properties properties) {
        super(properties);
        registerDefaultState(stateDefinition.any().setValue(FACING, Direction.NORTH));
    }

    @Override
    protected MapCodec<? extends BaseEntityBlock> codec() {
        return simpleCodec(TunerBlock::new);
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext ctx) {
        return defaultBlockState().setValue(FACING, ctx.getHorizontalDirection().getOpposite());
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext ctx) {
        return SHAPE;
    }

    @Override
    protected RenderShape getRenderShape(BlockState state) {
        return RenderShape.MODEL;
    }

    @Override
    public @Nullable BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new TunerBlockEntity(pos, state);
    }

    @Override
    public @Nullable <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level, BlockState state, BlockEntityType<T> type) {
        return level.isClientSide() ? null : createTickerHelper(type, RadioAmpContent.TUNER_BE.get(), TunerBlockEntity::serverTick);
    }

    @Override
    public void setPlacedBy(Level level, BlockPos pos, BlockState state, @Nullable LivingEntity placer, ItemStack stack) {
        super.setPlacedBy(level, pos, state, placer, stack);
        if (!level.isClientSide() && placer instanceof Player p && level.getBlockEntity(pos) instanceof TunerBlockEntity be)
            be.setOwner(p.getUUID());
    }

    @Override
    protected InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos, Player player, BlockHitResult hit) {
        if (!level.isClientSide() && level.getBlockEntity(pos) instanceof TunerBlockEntity be)
            player.sendSystemMessage(Component.literal(be.statusLine()));
        return InteractionResult.sidedSuccess(level.isClientSide());
    }
}
